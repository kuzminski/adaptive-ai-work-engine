#!/usr/bin/env python3
"""Generate docs/STATUS.md from code (roadmap 0.4): version, feature statuses, pytest test count.

The feature table lives here (one place) so README and reports cannot drift into contradictory statuses;
`test_status_consistency.py` fails when a version or a locked-mode claim disagrees with the code.
Usage: python status_page.py [--count-tests] [--out docs/STATUS.md]
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import adaptive_policy
import product_version

ROOT = Path(__file__).resolve().parent

# status vocabulary: RELEASED | IMPLEMENTED | EXPERIMENTAL | LOCKED | PLANNED
FEATURES = [
    ("Product app (portable build, process view, STOP/RESUME, Human Gate)", "RELEASED", ""),
    ("Autonomy controller (PLAN-EXECUTE-VERIFY-REVIEW-REPAIR), fail-closed transactional merge", "IMPLEMENTED", ""),
    ("Telemetry: one AAW_TELEMETRY_V1 record per call, one price source", "IMPLEMENTED", ""),
    ("Analytics index (cost, usage, telemetry authority)", "IMPLEMENTED", ""),
    ("Adaptive evidence loop (Gate label, SHADOW report)", "IMPLEMENTED", "reports only; never unlocks a mode"),
    ("Adaptive mode SHADOW (passive)", "IMPLEMENTED", ""),
    ("Adaptive mode CONTROLLED_ADAPTIVE / ACTIVE", "LOCKED", "needs signed authorization and real data (roadmap stage 4)"),
    ("Strategy simulator (empirical_benchmark)", "EXPERIMENTAL", "SIMULATED numbers, not measurements"),
    ("Real-work benchmark (aaw_experience, BENCH/)", "EXPERIMENTAL", "live validation pending"),
]


def adaptive_locked() -> bool:
    """True while the code refuses to authorize CONTROLLED_ADAPTIVE / ACTIVE (checked against a throwaway root)."""
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        authorized, _reason, _data = adaptive_policy.verify_controlled_mode_authorization(Path(tmp))
    return not authorized


def count_tests() -> int | None:
    proc = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q"], cwd=ROOT,
                          capture_output=True, text=True)
    found = re.findall(r"(\d+) tests? collected", proc.stdout)
    return int(found[-1]) if found else None


def render(tests: int | None = None) -> str:
    lines = [f"# AAW status - release {product_version.RELEASE}", "",
             "_Generated by `python status_page.py` from code; do not edit by hand._", "",
             f"- Release: `{product_version.RELEASE}` ({product_version.RELEASE_NAME}, {product_version.RELEASE_DATE})",
             f"- Engine base: {product_version.ENGINE_BASE}",
             f"- Tests collected: {tests if tests is not None else 'n/a (run with --count-tests)'}",
             f"- Adaptive modes CONTROLLED_ADAPTIVE / ACTIVE locked: {'yes' if adaptive_locked() else 'NO'}", "",
             "| Feature | Status | Note |", "|---|---|---|"]
    for name, status, note in FEATURES:
        lines.append(f"| {name} | {status} | {note} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "STATUS.md")
    parser.add_argument("--count-tests", action="store_true")
    args = parser.parse_args(argv)
    args.out.write_text(render(count_tests() if args.count_tests else None), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
